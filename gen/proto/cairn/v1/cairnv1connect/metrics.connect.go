// Metrics and user settings.
//
// Cairn separates two concepts that platforms often conflate:
//
//   * Settings — fixed user state. Height, birthdate, gender, units, locale.
//     Per-activity-type training thresholds (FTP, LTHR, threshold pace).
//     Per-activity-type source priorities. Per-provider auto-update rules.
//
//   * Metrics — time-series of measurements or computed values. Weight,
//     resting HR, HRV, steps, sleep. Training load: TSS per activity (also
//     stored on Activity.summary), and daily CTL/ATL/TSB rollups computed
//     by the Core.
//
// "Current weight" is the latest metric value for key="weight_kg" — not a
// settings field. Domain code uses GetCurrentUserContext to assemble a
// composite (settings + latest metrics) when computing things like TSS.

