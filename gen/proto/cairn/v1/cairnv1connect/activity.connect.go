// Activities form the core of Cairn's domain model.
//
// An Activity is a single workout. It is the merged view of one or more
// ActivitySources — different external systems may report on the same
// workout (a Strava activity and the corresponding Garmin Connect activity
// for the same ride). Sources keep their raw and parsed payloads
// independently; the Activity's fields are computed by the Core's merge
// engine using the user's per-activity-type source priorities.
//
// Streams (time-series) are NOT merged across sources — each source keeps
// its own stream. The frontend renders the stream from the highest-priority
// source for the gps_track field group, and lets the user toggle between
// sources for comparison.

